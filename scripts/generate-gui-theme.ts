// Regenerates src/components/next/gui-theme.css from the downloaded Graphical theme reference.
import { readFileSync, writeFileSync } from 'node:fs'

const source = 'gui/themes/roundtable.md'
const target = 'src/components/next/gui-theme.css'
const markdown = readFileSync(source, 'utf8')

function variables(mode: 'light' | 'dark') {
  const section = markdown.split(`## ${mode} CSS variables`)[1]?.split('\n## ')[0]
  if (!section) throw new Error(`Missing ${mode} variables in ${source}.`)
  return [...section.matchAll(/^\| `(--[\w-]+)` \| (.+?) \|$/gm)].map(([, name, value]) => {
    // The theme names its own family alias; this app loads Geist through Fontsource.
    const resolved = value!.replaceAll('"Sidebar Geist"', "'Geist Variable'")
    return `  ${name}: ${resolved};`
  })
}

writeFileSync(
  target,
  `/* Generated by scripts/generate-gui-theme.ts from ${source}. Local choices live in gui-local.css. */
.gui-roundtable {
  color-scheme: dark;
${variables('dark').join('\n')}
}

.gui-roundtable[data-mode='light'] {
  color-scheme: light;
${variables('light').join('\n')}
}
`,
)
console.log(`Wrote ${target}`)
